#!/usr/bin/env bash
# Generate status/STATUS.md: a table of all 437 cells grouped by category, with
# close status, time, and links to the log, the layout render, and the output files.
# Reads status/results.tsv if it exists (cell<TAB>status<TAB>time_s), otherwise
# every cell shows as pending. Run src/cellgen/run_status.sh to produce results.tsv.
set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MAP="$ROOT/recipes/cell_categories.tsv"
RES="$ROOT/status/results.tsv"
OUT="$ROOT/status/STATUS.md"
mkdir -p "$ROOT/status"

declare -A TITLE=(
  [inverter]="Inverters" [buffer]="Buffers" [and_or]="AND / OR gates"
  [nand_nor]="NAND / NOR gates" [aoi]="AND OR Invert (AOI)" [oai]="OR AND Invert (OAI)"
  [xor_xnor]="XOR / XNOR" [mux]="Multiplexers" [adder]="Adders / majority"
  [tristate]="Tristate / enabled drivers" [flipflop]="Flip flops" [latch]="Latches"
  [clock_delay]="Clock & delay" [tie_probe]="Tie & probe" [fill_phys]="Fill / physical"
  [lpflow_pwr]="Low power / level shift / isolation")
ORDER="inverter buffer and_or nand_nor aoi oai xor_xnor mux adder tristate flipflop latch clock_delay tie_probe fill_phys lpflow_pwr"

total=$(wc -l < "$MAP")
have_res=0; [ -f "$RES" ] && have_res=1

# cell -> "status\ttime" (pending if not in results)
lookup(){ awk -F'\t' -v c="$1" '$1==c{print $2"\t"$3; f=1} END{if(!f)print "pending\t"}' "$RES" 2>/dev/null || printf 'pending\t'; }

{
echo "# Cell Status"
echo
echo "Place and route status for all **$total** \`sky130_fd_sc_hd\` cells, grouped by category."
echo "**Status** is whether the cell builds DRC and LVS clean on the current flow (its committed recipe)."
echo "Each row links to the verbose run **log**, a **layout** render you can view in the browser, and the raw **output files** (GDS and LEF)."
echo
if [ "$have_res" = 1 ]; then
  cl=$(awk -F'\t' '$2=="closed"{n++}END{print n+0}' "$RES")
  op=$(awk -F'\t' '$2=="open"{n++}END{print n+0}' "$RES")
  echo "**$cl closed, $op open, of $total.** Last run recorded in \`status/results.tsv\`."
else
  echo "> Not run yet. Every cell shows as **pending**; run \`src/cellgen/run_status.sh\` to populate the statuses, times, logs, renders, and outputs."
fi
echo
for cat in $ORDER; do
  n=$(awk -F'\t' -v C="$cat" '$2==C{n++}END{print n+0}' "$MAP")
  echo "## ${TITLE[$cat]} ($n)"
  echo
  echo "| Cell | Status | Time (s) | Log | Layout | Files |"
  echo "|---|---|--:|---|---|---|"
  awk -F'\t' -v C="$cat" '$2==C{print $1}' "$MAP" | sort | while read -r cell; do
    IFS=$'\t' read -r st tm < <(lookup "$cell")
    case "$st" in
      closed) icon="✅ closed" ;;
      open)   icon="❌ open" ;;
      *)      icon="⏳ pending" ;;
    esac
    printf '| `%s` | %s | %s | [log](logs/%s.log) | [view](renders/%s.png) | [gds+lef](outputs/%s/) |\n' \
      "$cell" "$icon" "${tm:-}" "$cell" "$cell" "$cell"
  done
  echo
done
echo "---"
echo "_Generated by \`src/cellgen/gen_status.sh\` from \`recipes/cell_categories.tsv\` and \`status/results.tsv\`._"
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
